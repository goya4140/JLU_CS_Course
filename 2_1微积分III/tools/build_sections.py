"""Group the existing tutorial into textbook Sections; retain full-chapter URLs.

Edit the two original tutorial Markdown files for lesson content, the chapter*/
homework*.md files for homework, and course_structure.json for grouping. Other
chapter*/ Markdown files are generated by this script.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STRUCTURE = json.loads((ROOT / 'tools/course_structure.json').read_text())


def topics_in(text):
    matches = list(re.finditer(r'^## (\d+) (.+)$', text, re.M))
    return {
        int(match[1]): text[match.start():matches[i + 1].start() if i + 1 < len(matches) else len(text)].strip()
        for i, match in enumerate(matches)
    }


def lesson_text(text):
    # Topic numbers belonged to the former long chapter, not textbook Sections.
    text = re.sub(r'^(#{2,3}) \d+(?:\.\d+)? ', r'\1 ', text, flags=re.M)
    return text.replace('](assets/', '](../assets/').replace('](chapter4/', '](../chapter4/').replace('](chapter5/', '](../chapter5/')


def build():
    for chapter in STRUCTURE['chapters']:
        number = chapter['number']
        directory = ROOT / f'chapter{number}'
        directory.mkdir(exist_ok=True)
        original = (ROOT / chapter['source']).read_text()
        topics = topics_in(original)
        grouped = [topic for section in chapter['sections'] for topic in section['topics']]
        grouped += chapter['summary_topics']
        assert sorted(grouped) == sorted(topics), f'Chapter {number}: missing or repeated topics'
        rows = []
        total = 0
        for section in chapter['sections']:
            n = section['number']
            label = f'{number}.{n}'
            homework = directory / f'homework{n}.md'
            homework_text = homework.read_text()
            count = len(re.findall(r'^## .*作业 · ', homework_text, re.M))
            assert count, f'Missing homework for {label}'
            for field in ('**原题**', '**对应知识点**', '**解题过程**'):
                assert homework_text.count(field) == count, f'Missing {field} in {label}'
            total += count
            rows.append(f'| [{label} {section["title"]}](section{n}.md) | {section["goal"]} | [作业解读 · {count}题](homework{n}.md) |')
            header = (
                f'# {label} {section["title"]}\n\n'
                f'[第{number}章目录](README.md) · [作业解读（{count}题）](homework{n}.md)\n\n'
                f'> 学习目标：{section["goal"]}\n\n'
            )
            body = '\n\n'.join(lesson_text(topics[t]) for t in section['topics'])
            previous = f'[上一节：{number}.{n-1}](section{n-1}.md)' if n > 1 else '[本章导览](README.md)'
            following = f'[下一节：{number}.{n+1}](section{n+1}.md)' if n < len(chapter['sections']) else '[章末总结与自测](summary.md)'
            end = f'\n\n---\n\n[进入本节作业解读](homework{n}.md) · {previous} · {following}\n'
            (directory / f'section{n}.md').write_text(header + body + end)
        summary = f'# 第{number}章 总结与自测\n\n[本章目录](README.md)\n\n'
        summary += '\n\n'.join(lesson_text(topics[t]) for t in chapter['summary_topics'])
        summary += '\n\n[期末题型与真题推导](../06_期末题型与复习路线.md)\n'
        (directory / 'summary.md').write_text(summary)
        intro = (
            f'# 第{number}章 {chapter["title"]}\n\n'
            f'[课程首页](../README.md) · [整章连续阅读](../{chapter["source"]})\n\n'
            f'{chapter["goal"]}\n\n'
            f'本章按教材的 {len(chapter["sections"])} 个 Section 组织。先阅读本节教程，再进入对应作业；作业共 {total} 题，每题包含原题、1—2句话的知识点说明和解题过程。\n\n'
            '## Section 学习路线\n\n| Section | 学习目标 | 平时作业 |\n|---|---|---|\n'
            + '\n'.join(rows)
            + f'\n\n## 本章整合\n\n- [章末方法总结与自测](summary.md)\n- [期末题型与真题推导](../06_期末题型与复习路线.md)\n- [资料依据与覆盖对照](../资料依据与覆盖对照.md)\n'
        )
        if number == 4:
            intro += '\n## 学习地图\n\n![第一型积分的讲解路线](../assets/map4.svg)\n\n图中的01—10是原教程的讲解单元：01—04归入4.1，05—06归入4.2，07—08归入4.3，09—10放在章末总结与自测。\n'
        (directory / 'README.md').write_text(intro)
    print('Built 8 textbook Sections and 2 chapter overviews; checked 42 homework records')


if __name__ == '__main__':
    build()
